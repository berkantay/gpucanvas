/**
 * Fictional products the playground's screens are made for. Every cluster on the canvas is one
 * product, so the same screen layout shows up with a different brand, copy and data each time.
 */
export type Tone = 'lime' | 'yellow' | 'rose' | 'blue' | 'purple' | 'cyan' | 'gray';

export interface Entry {
  title: string;
  sub: string;
  value: string;
  status: string;
  tone: Tone;
}

export interface Product {
  name: string;
  tagline: string;
  /** Brand colour; the frame derives the whole accent scale from it. */
  brand: string;
  icon: RemixiconComponentType;
  nav: string[];
  /** What the product lists: "Transactions", "Tracks", "Trips". */
  things: string;
  entries: Entry[];
  kpis: [label: string, value: string, delta: string][];
  /** The one number or item the product is about, for hero cards. */
  hero: { label: string; value: string; sub: string };
  /** Short phrases for feature cards, pricing and onboarding. */
  features: string[];
  /** Covers for hero areas and galleries, drawn from a seed (see art.ts). */
  images: string[];
}

const e = (title: string, sub: string, value: string, status: string, tone: Tone): Entry => ({
  title,
  sub,
  value,
  status,
  tone,
});

